"""Bitmap fonts for FM80S, from BDF files (the firmware stores no hand-written glyphs).

    python3 tools/gen_font.py build/gen/font.h NAME=FILE.bdf[:TOP:ROWS] ...

Each NAME=FILE gives one monospace face, ASCII 32..126, one byte per row with bit 7 the leftmost
pixel (width <= 8). TOP:ROWS keeps ROWS rows from row TOP: a face cut to a smaller cell. The cut
must keep every pixel of the interface's characters (upper case, digits, the symbols in KEEP); the
lower-case descenders it loses are listed. Python 3.9+, standard library only, deterministic.

The faces are Terminus (Dimitar Toshkov Zhekov, SIL OFL 1.1, assets/fonts/Terminus-LICENSE.txt):
12 px (6x12) and 16 px (8x16), the cut ones are modified versions (P1-04, ADR-027). The generated
data stays under the OFL.
"""
import sys
from pathlib import Path

FIRST, LAST = 32, 126
KEEP = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789#-_.:/+<>[]()=*!?%&"


def parse(path):
    """(width, height, {code: [row bits, top to bottom]}) of a monospace BDF font"""
    box, glyphs, cur, rows = None, {}, None, None
    for line in Path(path).read_text(encoding="latin-1").splitlines():
        f = line.split()
        if not f:
            continue
        if f[0] == "FONTBOUNDINGBOX":
            box = tuple(int(v) for v in f[1:5])
        elif f[0] == "ENCODING":
            cur = int(f[1])
        elif f[0] == "BBX":
            assert box and tuple(int(v) for v in f[1:5]) == box, f"glyph {cur}: BBX {f[1:5]} != {box}"
        elif f[0] == "BITMAP":
            rows = []
        elif f[0] == "ENDCHAR":
            if FIRST <= cur <= LAST:
                assert len(rows) == box[1], f"glyph {cur}: {len(rows)} rows"
                glyphs[cur] = rows
            cur, rows = None, None
        elif rows is not None:
            assert len(f[0]) == 2, f"glyph {cur}: row {f[0]}"
            rows.append(int(f[0], 16))
    assert box, "no FONTBOUNDINGBOX"
    w, h = box[0], box[1]
    assert w <= 8, f"width {w}: one byte per row"
    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    assert not missing, f"missing glyphs {missing}"
    return w, h, glyphs


def face(spec):
    """(name, file, width, height, {code: rows}) of NAME=FILE[:TOP:ROWS]"""
    name, rest = spec.split("=", 1)
    parts = rest.split(":")
    w, h, glyphs = parse(parts[0])
    if len(parts) == 3:
        top, rows = int(parts[1]), int(parts[2])
        assert 0 <= top and top + rows <= h, f"{spec}: rows outside the face"
        for c in KEEP:
            lost = [i for i, r in enumerate(glyphs[ord(c)]) if r and not top <= i < top + rows]
            assert not lost, f"{spec}: {c!r} loses rows {lost}"
        cut = "".join(chr(c) for c, g in sorted(glyphs.items())
                      if any(r for i, r in enumerate(g) if not top <= i < top + rows))
        print(f"gen_font: {name} {w}x{rows} from {Path(parts[0]).name} rows {top}..{top + rows - 1}"
              f" (clipped: {cut or 'nothing'})")
        glyphs = {c: g[top:top + rows] for c, g in glyphs.items()}
        h = rows
    return name, parts[0], w, h, glyphs


def main(dst, specs):
    L = ["/* SPDX-License-Identifier: OFL-1.1 */",
         "/* generated by tools/gen_font.py: do not edit */",
         "/* Terminus font, Copyright (C) 2020 Dimitar Toshkov Zhekov, SIL Open Font License 1.1;",
         " * the cut faces are modified versions of it (ADR-027) */",
         "#pragma once",
         "#include <stdint.h>",
         "",
         "#define FONT_FIRST %d" % FIRST,
         "#define FONT_LAST %d" % LAST,
         "#define FONT_GLYPHS %d" % (LAST - FIRST + 1),
         ""]
    for spec in specs:
        name, src, w, h, glyphs = face(spec)
        L += ["/* %s: %dx%d from %s; one row per byte, top to bottom, bit 7 = leftmost pixel */"
              % (name, w, h, Path(src).name),
              "#define %s_W %d" % (name, w),
              "#define %s_H %d" % (name, h),
              "static const uint8_t %s[%d][%d] = {" % (name, LAST - FIRST + 1, h)]
        for c in range(FIRST, LAST + 1):
            L.append("    {%s}, /* %s */" % (", ".join("0x%02X" % r for r in glyphs[c]),
                                            chr(c) if chr(c) not in "*/\\" else "0x%02X" % c))
        L += ["};", ""]
    Path(dst).parent.mkdir(parents=True, exist_ok=True)
    Path(dst).write_text("\n".join(L))


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2:])
